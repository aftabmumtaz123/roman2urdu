function romanizeUrduWord(word) {
  if (urduToRomanMap[word]) return urduToRomanMap[word];
  // Handle common name compounds with spaces as well as joined Urdu spellings.
  const normalized = word.replace(/[ًٌٍَُِّْٰ]/g, "");
  if (urduToRomanMap[normalized]) return urduToRomanMap[normalized];
  return [...normalized].map((ch, i, chars) => {
    if (ch === "و" && i > 0 && i < chars.length - 1) return "o";
    return urduLetterMap[ch] ?? ch;
  }).join("");
}

export function urduToRoman(text = "") {
  let value = String(text);
  // Phrase-level rules produce natural Roman Urdu for frequent sentence patterns.
  const phraseRules = [
    [/میرا\s*نام\s*(?:عبدالرحمن|عبدالرحمان|عبد\s*الرحمن|عبد\s*الرحمان)\s*ہے/g, "Mera naam Abdul Rehman hai"],
    [/السلام\s*علیکم/g, "Assalam o alaikum"],
    [/وعلیکم\s*السلام/g, "Wa alaikum assalam"],
    [/مجھے\s*اردو\s*پسند\s*ہے/g, "Mujhe Urdu pasand hai"],
    [/آپ\s*کیسے\s*ہیں/g, "Aap kaise hain"],
    [/آپ\s*کیسی\s*ہیں/g, "Aap kaisi hain"],
    [/کیا\s*حال\s*ہے/g, "Kya haal hai"]
  ];
  for (const [pattern, replacement] of phraseRules) value = value.replace(pattern, replacement);
  // Tokenize Urdu words and punctuation separately so punctuation and spacing survive.
  return value.replace(/[\u0600-\u06FF]+(?:\s+[\u0600-\u06FF]+)*/gu, (phrase) => {
    const words = phrase.split(/(\s+)/u);
    return words.map(token => /^\s+$/.test(token) ? token : romanizeUrduWord(token)).join("");
  }).replace(/؟/g, "?").replace(/،/g, ",").replace(/۔/g, ".");
}
